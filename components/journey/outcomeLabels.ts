import type { ExerciseOutcome } from "./state";

// Подпись итога упражнения, которое закончилось без проверки ответа: время вышло
// или свободный ответ пропущен без оценки, потому что модель была недоступна.
// Общая для карточки упражнения и для карточки после перезагрузки страницы
export function skippedLabel(outcome: ExerciseOutcome): string {
  if (outcome.unrated) {
    return outcome.skipped
      ? "Ответ не оценён — оценка была недоступна"
      : "Засчитана первая попытка — оценка была недоступна";
  }
  return outcome.skipped ? "Время вышло — ответа нет" : "Время вышло — засчитана первая попытка";
}
