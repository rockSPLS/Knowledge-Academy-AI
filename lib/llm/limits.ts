// Ограничения запросов к языковой модели. Файл без server-only: длину текста
// проверяет сервер, а позже её же будет показывать и проверять форма ввода в браузере.

// Максимальная длина темы или вставленного текста, символов. Хватает на большую
// статью (примерно 3 тысячи слов), но не на книгу: длинный текст дорог для модели
// и плохо разбивается на одно путешествие
export const MAX_SOURCE_LENGTH = 20_000;

// Максимальный размер тела запроса к модели, байт. Проверяется до разбора JSON,
// чтобы огромный запрос не читался в память целиком. С запасом: в JSON один символ
// текста занимает до 6 байт (\uXXXX), плюс служебные поля
export const MAX_REQUEST_BYTES = MAX_SOURCE_LENGTH * 6 + 1024;

// «Мягкий» лимит частоты генерации на один IP: столько путешествий за окно
export const RATE_LIMIT_PER_IP = 5;
export const RATE_LIMIT_PER_IP_WINDOW_MS = 10 * 60 * 1000;

// Общий лимит на экземпляр сервера (все посетители вместе) — на случай запросов
// с множества разных IP
export const RATE_LIMIT_GLOBAL = 60;
export const RATE_LIMIT_GLOBAL_WINDOW_MS = 60 * 60 * 1000;

// Лимит оценки ответов моделью — свой счётчик, отдельно от генерации: в путешествии
// не больше двух свободных ответов по две попытки и одна калибровка с одной попыткой,
// то есть до 5 оценок («Показать ответ» модель не вызывает). Лимиты — это лимиты
// генерации × 5: любое разрешённое путешествие можно пройти целиком, не упираясь в лимит на полпути
const EVALUATIONS_PER_JOURNEY = 5;
export const EVALUATION_LIMIT_PER_IP = RATE_LIMIT_PER_IP * EVALUATIONS_PER_JOURNEY;
export const EVALUATION_LIMIT_GLOBAL = RATE_LIMIT_GLOBAL * EVALUATIONS_PER_JOURNEY;

// Поиск по материалам: максимальная длина вопроса, символов. Вопрос — одна-две фразы;
// длинный текст поиск не улучшает, а запрос к модели делает дороже
export const MAX_QUESTION_LENGTH = 300;
export const MAX_SEARCH_REQUEST_BYTES = MAX_QUESTION_LENGTH * 6 + 1024;

// Лимит поиска — свой счётчик, отдельно от генерации и оценки. Один поиск — это эмбеддинг
// вопроса и короткий ответ модели. 20 вопросов за 10 минут хватает, чтобы пройти
// по нескольким темам и переспросить; общий лимит — как у оценки
export const SEARCH_LIMIT_PER_IP = 20;
export const SEARCH_LIMIT_GLOBAL = EVALUATION_LIMIT_GLOBAL;
