export type PromptFragment =
  | { kind: "section"; path: string[]; text: string }
  | { kind: "exercise"; path: string[]; question: string };

export function answerPrompt(question: string, fragments: PromptFragment[]): string {
  const ask = dataTag("question");
  const list = fragments
    .map((fragment, index) => {
      const tag = dataTag(`fragment-${index + 1}`);
      const body =
        fragment.kind === "section"
          ? `Раздел статьи: ${fragment.path.join(" › ")}\n${fragment.text}`
          : `Упражнение в разделе: ${fragment.path.join(" › ")}\nВопрос упражнения: ${fragment.question}`;
      return `Фрагмент [${index + 1}]:\n${tag.open}\n${body}\n${tag.close}`;
    })
    .join("\n\n");
  return (
    `Ответь на вопрос человека по фрагментам материалов.\n\n` +
    `Вопрос:\n${ask.open}\n${question}\n${ask.close}\n\n` +
    `Фрагменты:\n\n${list}`
  );
}
