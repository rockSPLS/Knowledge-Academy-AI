export type PromptFragment =
  | { kind: "section"; path: string[]; text: string }
  // checkpoint — название чекпоинта (понятие), concept — что нужно понять, text — конспект
  | { kind: "journey"; journeyTitle: string; checkpoint: string; concept: string; text: string }
  // answered — человек уже отвечал на упражнение: его последний итог и объяснение верного ответа
  | {
      kind: "exercise";
      path: string[];
      question: string;
      answered?: { verdict: "correct" | "partial" | "incorrect"; explanation: string };
    };

const VERDICT_TEXT = { correct: "верно", partial: "частично верно", incorrect: "неверно" };

function fragmentBody(fragment: PromptFragment): string {
  switch (fragment.kind) {
    case "section":
      return `Раздел статьи: ${fragment.path.join(" › ")}\n${fragment.text}`;
    case "journey":
      return (
        `Путешествие человека «${fragment.journeyTitle}», понятие «${fragment.checkpoint}»\n` +
        `Что нужно понять: ${fragment.concept}\nКонспект: ${fragment.text}`
      );
    case "exercise":
      return (
        `Упражнение в разделе: ${fragment.path.join(" › ")}\nВопрос упражнения: ${fragment.question}` +
        (fragment.answered
          ? `\nПоследний ответ человека на это упражнение: ${VERDICT_TEXT[fragment.answered.verdict]}.\nОбъяснение верного ответа: ${fragment.answered.explanation}`
          : "")
      );
  }
}

// progress — блок «Прогресс» (lib/search/progress.ts). Фрагментов может не быть:
// тогда модель отвечает только по прогрессу (вопрос о самом человеке)
export function answerPrompt(question: string, fragments: PromptFragment[], progress: string): string {
  const ask = dataTag("question");
  const progressTag = dataTag("progress");
  const list =
    fragments.length > 0
      ? fragments
          .map((fragment, index) => {
            const tag = dataTag(`fragment-${index + 1}`);
            return `Фрагмент [${index + 1}]:\n${tag.open}\n${fragmentBody(fragment)}\n${tag.close}`;
          })
          .join("\n\n")
      : "Поиск не нашёл фрагментов по этому вопросу.";
  return (
    `Ответь на вопрос человека по фрагментам материалов и его прогрессу.\n\n` +
    `Вопрос:\n${ask.open}\n${question}\n${ask.close}\n\n` +
    `Фрагменты:\n\n${list}\n\n` +
    `Прогресс:\n${progressTag.open}\n${progress}\n${progressTag.close}`
  );
}
