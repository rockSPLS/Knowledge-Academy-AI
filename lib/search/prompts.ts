import "server-only";
import { randomBytes } from "node:crypto";

// Промпт ответа поиска по материалам портала: модель отвечает на вопрос только
// по найденным фрагментам и прогрессу человека и ссылается на фрагменты номерами [N].
// Версия 2 (итерация 2): фрагменты путешествий, объяснение упражнения, на которое человек
// уже отвечал, и блок «Прогресс» — ответы и на вопросы о себе («где я ошибался?»).
// Версии — в docs/prompts-journal.md.
//
// Защита от инъекции промпта — как в путешествиях (lib/journey/prompts.ts):
// вопрос и каждый фрагмент передаются между метками со случайной частью, текст
// не может «закрыть» блок, не зная метки; системный промпт говорит, что внутри —
// данные, а не инструкции. Ответ ограничен схемой, номера источников сервер проверяет сам.

// Метка блока данных: случайная часть делает её непредсказуемой для автора текста
function dataTag(name: string): { open: string; close: string } {
  const tag = `${name}-${randomBytes(6).toString("hex")}`;
  return { open: `<${tag}>`, close: `</${tag}>` };
}

