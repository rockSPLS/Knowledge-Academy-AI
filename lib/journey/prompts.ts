export function exercisesPrompt(
  plan: Plan,
  checkpoint: PlanCheckpoint,
  layout: CheckpointLayout,
  number: number,
): string {
  const { open, close } = dataTag("checkpoint");
  const list = (items: string[]) =>
    items
      .filter((item) => item.trim() !== "")
      .map((item) => `- ${item}`)
      .join("\n") || "- нет";
  const card = [
    `Путешествие: ${plan.title}`,
    `Чекпоинт ${number} из ${plan.checkpoints.length}: ${checkpoint.title}`,
    `Понятие: ${checkpoint.concept}`,
    `Конспект: ${checkpoint.summary}`,
    `Ключевые факты:\n${list(checkpoint.keyFacts)}`,
    `Типичные заблуждения:\n${list(checkpoint.misconceptions)}`,
    // Сомнительные утверждения исходного текста: из них можно делать неверные варианты,
    // но не верные ответы
    ...(plan.doubts.length > 0
      ? [
          `Утверждения исходного материала, которые расходятся с общепринятыми сведениями (верными ответами их не делай):\n${plan.doubts.map((doubt) => `- ${doubt.claim}`).join("\n")}`,
        ]
      : []),
  ].join("\n");
  // Типы и вид — значения из списков, их назначил сервер (layout.ts)
  return (
    `Составь упражнения типов: ${layout.types.join(", ")}.` +
    (layout.freeAnswerKind === null ? "" : ` Вид свободного ответа: ${layout.freeAnswerKind}.`) +
    (layout.spare === null ? "" : ` Запасное упражнение — последним, тип: ${layout.spare}.`) +
    "\n\n" +
    `Карточка чекпоинта:\n${open}\n${card}\n${close}`
  );
}

// Добавка к промпту при повторе: что было не так в прошлом ответе
