export function exercisesPrompt(plan: Plan, checkpoint: PlanCheckpoint, number: number): string {
  const { open, close } = dataTag("checkpoint");
  const card = [
    `Путешествие: ${plan.title}`,
    `Чекпоинт ${number} из ${plan.checkpoints.length}: ${checkpoint.title}`,
    `Понятие: ${checkpoint.concept}`,
    `Конспект: ${checkpoint.summary}`,
    `Ключевые факты:\n${checkpoint.keyFacts.map((fact) => `- ${fact}`).join("\n")}`,
    `Типичные заблуждения:\n${checkpoint.misconceptions.map((item) => `- ${item}`).join("\n") || "- нет"}`,
    // Сомнительные утверждения исходного текста: из них можно делать неверные варианты,
    // но не верные ответы
    ...(plan.doubts.length > 0
      ? [
          `Утверждения исходного материала, которые расходятся с общепринятыми сведениями (верными ответами их не делай):\n${plan.doubts.map((doubt) => `- ${doubt.claim}`).join("\n")}`,
        ]
      : []),
  ].join("\n");
  return (
    `Составь упражнения типов: ${checkpoint.exerciseTypes.join(", ")}.\n\n` +
    `Карточка чекпоинта:\n${open}\n${card}\n${close}`
  );
}

// Добавка к промпту при повторе: что было не так в прошлом ответе
export function retryNote(error: string | null): string {
  return error
    ? `\n\nПредыдущий ответ отклонён проверкой: ${error}. Исправь это и соблюдай все правила.`
    : "\n\nПредыдущий ответ не подошёл под схему. Ответь строго по схеме.";
}
