// Промпты генерации путешествия и оценки свободных ответов. Генерация — цепочка из двух шагов:
// 1) план — разбор материала на чекпоинты (по одному понятию) с конспектом,
//    ключевыми фактами и типичными заблуждениями;
// 2) упражнения — отдельный запрос на каждый чекпоинт; он получает не исходный
//    текст, а карточку чекпоинта из шага 1.
//
// Защита от инъекции промпта: материал пользователя и карточки чекпоинтов
// передаются между метками со случайной частью — текст не может «закрыть» блок,
// не зная метки; системный промпт говорит, что внутри — данные, а не инструкции.
// Ответ ограничен схемой и проверками (build.ts), инструментов у модели нет.
// Оценка свободного ответа (шаг 3, при прохождении) — так же: ответ пользователя
// и данные упражнения передаются между метками.

// Метка блока данных: случайная часть делает её непредсказуемой для автора текста
function dataTag(name: string): { open: string; close: string } {
  const tag = `${name}-${randomBytes(6).toString("hex")}`;
  return { open: `<${tag}>`, close: `</${tag}>` };
}

