// Как вид задания звучит для оценщика
const KIND_LABELS: Record<FreeAnswerKind, string> = {
  explain: "развёрнутый ответ",
  simple: "объяснить простыми словами",
  friend: "объяснить другу, который заблуждается",
  example: "привести свой пример",
};

export function judgePrompt(exercise: FreeAnswerExercise, answer: string): string {
  const task = dataTag("task");
  const reply = dataTag("answer");
  const card = [
    `Вид задания: ${KIND_LABELS[exercise.kind]}`,
    `Вопрос: ${exercise.question}`,
    `Критерии:\n${exercise.criteria.map((criterion, index) => `${index + 1}. ${criterion.text}`).join("\n")}`,
    `Образец ответа: ${exercise.sample}`,
  ].join("\n");
  return (
    `Оцени ответ ученика по критериям.\n\n` +
    `Задание:\n${task.open}\n${card}\n${task.close}\n\n` +
    `Ответ ученика:\n${reply.open}\n${answer}\n${reply.close}`
  );
}
